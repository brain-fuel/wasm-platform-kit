// Direct WIT-to-Haskell generation. Canonical layouts and function signatures
// are supplied by upstream wit-parser, never inferred from Haskell layout.
// ref:DEC-host-sdk-direct-haskell
import {execFileSync} from 'node:child_process';
import {mkdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {generatorPath} from './paths.mjs';

/** Generates typed Haskell modules from upstream-resolved WIT. */
export async function generateBindings({wit, world, out})
{
  const metadata = JSON.parse(
    execFileSync(generatorPath(), ['describe', wit, world], {
      maxBuffer: 32 * 1024 * 1024,
    }),
  );
  const {resolve: schema, layouts, functions, resources} = metadata;
  const pascal = s =>
    s
      .split(/[^a-zA-Z0-9]/)
      .map(x => x.charAt(0).toUpperCase() + x.slice(1))
      .join('');
  const functionName = name =>
  {
    const renamed = name
      .replace(/^\[constructor\](.+)$/, '$1-new')
      .replace(/^\[(method|static)\]/, '')
      .replaceAll('.', '-');
    return renamed.replace(/-([a-z])/g, (_, x) => x.toUpperCase());
  };
  const guestResources = new Map(
    resources.filter(r => r.export).map(r => [r.id, r]),
  );
  const name = id =>
  {
    const t = schema.types[id];
    return t.name
      ? pascal(schema.interfaces[t.owner.interface].name) + pascal(t.name)
      : `T${id}`;
  };
  const hsType = t =>
  {
    if (typeof t === 'number')
    {
      const definition = schema.types[t];
      if (definition.name) return name(t);
      const value = definition.kind;
      if (value.result)
        return `(Either ${value.result.err == null ? '()' : hsType(value.result.err)} ${value.result.ok == null ? '()' : hsType(value.result.ok)})`;
      if (value.option !== undefined) return `(Maybe ${hsType(value.option)})`;
      if (value.list !== undefined)
        return value.list === 'u8' ? 'ByteString' : `[${hsType(value.list)}]`;
      if (value.handle) return hsType(value.handle.own ?? value.handle.borrow);
      if (value.type !== undefined) return hsType(value.type);
      return name(t);
    }
    const found = {
      string: 'Text',
      bool: 'Bool',
      u8: 'Word8',
      u16: 'Word16',
      u32: 'Word32',
      u64: 'Word64',
      s8: 'Int8',
      s16: 'Int16',
      s32: 'Int32',
      s64: 'Int64',
    }[t];
    if (!found) throw new Error(`unsupported WIT primitive: ${t}`);
    return found;
  };
  const codec = t =>
    t == null
      ? 'unitCodec'
      : typeof t === 'number'
        ? `c${t}`
        : ({
            string: 'textCodec',
            bool: 'boolCodec',
            u8: 'u8Codec',
            u16: 'u16Codec',
            u64: 'u64Codec',
            s8: 's8Codec',
            s16: 's16Codec',
            s32: 's32Codec',
            s64: 's64Codec',
            u32: 'u32Codec',
          }[t] ??
          (() =>
            {
            throw new Error(`unsupported ${t}`);
          })());
  const kind = t =>
    typeof t.kind === 'string' ? t.kind : Object.keys(t.kind)[0];
  const imports = `import Control.Exception (bracket)\nimport Control.Monad.IO.Class (liftIO)\nimport Control.Monad.Trans.State.Strict (runStateT)\nimport Data.Text (Text)\nimport Data.ByteString (ByteString)\nimport Data.Int\nimport Data.Word\nimport Foreign.Marshal.Alloc (free)\nimport Foreign.Ptr\nimport Foreign.Storable\nimport HostSDK.Canonical\n`;
  const typeNames = schema.types.map((_, id) => name(id));
  if (new Set(typeNames).size !== typeNames.length)
    throw new Error(
      'unsupported: colliding Haskell type names across WIT interfaces',
    );
  for (const direction of [true, false])
  {
    const names = functions
      .filter(f => f.export === direction)
      .map(f => functionName(f.function.name));
    if (new Set(names).size !== names.length)
      throw new Error(
        'unsupported: colliding Haskell function names across WIT interfaces',
      );
  }
  let types = `{-# LANGUAGE DuplicateRecordFields #-}\n{-# LANGUAGE ForeignFunctionInterface #-}\n-- Generated by wit-haskell. Do not edit.\nmodule Internal.Types where\n${imports}\n`;
  if (guestResources.size) types += 'import qualified ResourceTypes\n';
  const exported = [];
  for (const [id, t] of schema.types.entries())
  {
    const n = name(id),
      k = kind(t),
      v = t.kind[k],
      l = layouts[id];
    const c = `c${id}`;
    let declaration, load, store, lower, lift;
    if (k === 'resource' && guestResources.has(id))
    {
      types += `newtype ${n} = ${n} (GuestResource ResourceTypes.${n}) deriving (Eq, Show)\n${c} :: Codec ${n}\n${c} = mapCodec ${n} (\\(${n} x) -> x) (guestResourceCodec False)\n`;
      exported.push(n, 'new' + n, 'read' + n, 'drop' + n);
      continue;
    }
    if (k === 'resource')
    {
      declaration = `newtype ${n} = ${n} Word32 deriving (Eq, Show)`;
      load = `\\own p -> ${n} <$> load u32Codec own p`;
      store = `\\a p (${n} v) -> store u32Codec a p v`;
      lower = `\\a (${n} v) -> lower u32Codec a v`;
      lift = `\\own -> ${n} <$> liftValue u32Codec own`;
      exported.push(n);
    }
    else if (k === 'record')
    {
      const fields = v.fields,
        vars = fields.map((_, i) => `v${i}`);
      declaration = `data ${n} = ${n} { ${fields.map(f => `${n.charAt(0).toLowerCase() + n.slice(1) + pascal(f.name)} :: ${hsType(f.type)}`).join(', ')} } deriving (Eq, Show)`;
      load = `\\own p -> ${n}${fields.map((f, i) => ` ${i ? ' <*>' : '<$>'} load ${codec(f.type)} own (p \`plusPtr\` ${l.offsets[i]})`).join('')}`;
      store = `\\a p (${n} ${vars.join(' ')}) -> do\n${fields.map((f, i) => `      store ${codec(f.type)} a (p \`plusPtr\` ${l.offsets[i]}) v${i}`).join('\n')}${fields.length ? '' : '      pure ()'}`;
      lower = `\\a (${n} ${vars.join(' ')}) -> concat <$> sequence [${fields.map((f, i) => `lower ${codec(f.type)} a v${i}`).join(', ')}]`;
      lift = `\\own -> ${n}${fields.map((f, i) => ` ${i ? ' <*>' : '<$>'} liftValue ${codec(f.type)} own`).join('')}`;
      if (!fields.length)
      {
        load = '\\_ _ -> pure ' + n;
        lift = '\\_ -> pure ' + n;
      }
      exported.push(`${n}(..)`);
    }
    else if (['variant', 'enum', 'result', 'option'].includes(k))
    {
      let cases;
      if (k === 'variant' || k === 'enum')
      {
        cases = v.cases.map(x => ({
          ctor: n + pascal(x.name),
          type: x.type ?? null,
        }));
        declaration = `data ${n} = ${cases.map(x => x.ctor + (x.type === null ? '' : ` (${hsType(x.type)})`)).join(' | ')} deriving (Eq, Show)`;
        exported.push(`${n}(..)`);
      }
      else if (k === 'result')
      {
        cases = [
          {ctor: 'Right', type: v.ok ?? null, unit: true},
          {ctor: 'Left', type: v.err ?? null, unit: true},
        ];
        declaration = `type ${n} = Either ${v.err == null ? '()' : hsType(v.err)} ${v.ok == null ? '()' : hsType(v.ok)}`;
        if (t.name) exported.push(n);
      }
      else
      {
        cases = [
          {ctor: 'Nothing', type: null},
          {ctor: 'Just', type: v},
        ];
        declaration = `type ${n} = Maybe ${hsType(v)}`;
        if (t.name) exported.push(n);
      }
      const pattern = x =>
        x.ctor + (x.type !== null ? ' v' : x.unit ? ' ()' : '');
      const construct = (x, expression) =>
        x.type !== null
          ? `${x.ctor} <$> ${expression}`
          : `pure (${pattern(x)})`;
      const p = l.payload ?? 0,
        count = l.flat - 1;
      load = `\\own p -> do\n    tag <- peek p\n    case tag of\n${cases.map((x, i) => `      ${i} -> ${construct(x, `load ${codec(x.type)} own (p \`plusPtr\` ${p})`)}`).join('\n')}\n      _ -> fail "invalid ${n} discriminant"`;
      store = `\\a p value -> case value of\n${cases.map((x, i) => `    ${pattern(x)} -> poke p ${i}${x.type === null ? '' : ` >> store ${codec(x.type)} a (p \`plusPtr\` ${p}) v`}`).join('\n')}`;
      lower = `\\a value -> case value of\n${cases.map((x, i) => `    ${pattern(x)} -> ${x.type === null ? `pure (${i} : replicate ${count} 0)` : `(\\xs -> ${i} : pad ${count} xs) <$> lower ${codec(x.type)} a v`}`).join('\n')}`;
      lift = `\\own -> do\n    tag <- word\n    payload <- lanes ${count}\n    liftIO $ case tag of\n${cases.map((x, i) => `      ${i} -> ${construct(x, `runLift ${codec(x.type)} own payload`)}`).join('\n')}\n      _ -> fail "invalid ${n} discriminant"`;
    }
    else
    {
      let target;
      if (k === 'type') target = v;
      else if (k === 'handle') target = v.own ?? v.borrow;
      if (target !== undefined)
      {
        declaration = `type ${n} = ${hsType(target)}`;
        const borrowed =
          k === 'handle' &&
          v.borrow !== undefined &&
          guestResources.has(target);
        types += `${declaration}\n${c} :: Codec ${n}\n${c} = ${borrowed ? `mapCodec ${name(target)} (\\(${name(target)} x) -> x) (guestResourceCodec True)` : codec(target)}\n\n`;
      }
      else if (k === 'list')
      {
        types += `type ${n} = ${v === 'u8' ? 'ByteString' : `[${hsType(v)}]`}\n${c} :: Codec ${n}\n${c} = ${v === 'u8' ? 'bytesCodec' : `listCodec ${codec(v)}`}\n\n`;
      }
      else throw new Error(`unsupported ${k}`);
      if (t.name) exported.push(n);
      continue;
    }
    types += `${declaration}\n${c} :: Codec ${n}\n${c} = Codec ${l.size} ${l.flat}\n  (${load})\n  (${store})\n  (${lower})\n  (${lift})\n\n`;
  }
  const hostExports = [
    ...exported,
    ...functions.filter(f => !f.export).map(f => functionName(f.function.name)),
    ...resources.map(r => 'with' + name(r.id)),
  ];
  let host = `{-# LANGUAGE ForeignFunctionInterface #-}\n-- Generated by wit-haskell. Do not edit.\nmodule Host (${hostExports.join(', ')}) where\n${imports}\nimport Internal.Types\n`;
  let bindings = `{-# LANGUAGE ForeignFunctionInterface #-}\n-- Generated by wit-haskell. Do not edit.\nmodule Main where\n${imports}\nimport Internal.Types\nimport qualified Application\nmain :: IO ()\nmain = pure ()\n`;
  const mapping = {imports: {}, exports: {_initialize: 'sdk_core_initialize'}};
  const linker = ['hs_init', 'realloc', 'free', '_initialize'];
  for (const [index, f] of functions.entries())
  {
    const fn = f.function,
      result =
        fn.result === undefined || fn.result === null
          ? 'unitCodec'
          : codec(fn.result),
      raw = `sdk_fn_${index}`,
      binder = `sdkFn${index}`;
    const publicName = functionName(fn.name);
    const args = fn.params.map((_, i) => `a${i}`),
      rawargs = Array.from({length: f.params}, (_, i) => `r${i}`);
    const laneType = lane =>
      ['I64', 'PointerOrI64'].includes(lane) ? 'Word64' : 'Word32';
    const signature = f.paramLanes
      .map(laneType)
      .concat([f.results ? `IO ${laneType(f.resultLanes[0])}` : 'IO ()'])
      .join(' -> ');
    if (f.export)
    {
      mapping.exports[raw] = `${f.module}#${fn.name}`;
      mapping.exports[`sdk_post_${index}`] = `cabi_post_${f.module}#${fn.name}`;
      linker.push(raw, `sdk_post_${index}`);
      bindings += `\nforeign export ccall "${raw}" ${binder} :: ${signature}\n${binder} :: ${signature}\n${binder} ${rawargs.join(' ')} = withGuestCall $ ${f.retptr ? `exportResult ${result}` : f.results ? `exportScalar ${result}` : 'id'} $ do\n`;
      if (f.indirectParams)
      {
        bindings += fn.params
          .map(
            (p, i) =>
              `  a${i} <- load ${codec(p.type)} Owned (pointer r0 \`plusPtr\` ${f.paramOffsets[i]})\n`,
          )
          .join('');
        bindings += '  freeOwned Owned (pointer r0)\n';
      }
      else
        bindings += `  ((${args.length === 1 ? args[0] : `(${args.join(', ')})`}), _) <- runStateT (do\n${fn.params.map((p, i) => `    a${i} <- liftValue ${codec(p.type)} Owned`).join('\n')}\n    pure ${args.length === 1 ? args[0] : `(${args.join(', ')})`}) [${rawargs.map(x => 'fromIntegral ' + x).join(', ')}]\n`;
      bindings += `  Application.${publicName} ${args.join(' ')}\n`;
      const postSignature = f.resultLanes
        .map(laneType)
        .concat(['IO ()'])
        .join(' -> ');
      bindings += `foreign export ccall "sdk_post_${index}" sdkPost${index} :: ${postSignature}\nsdkPost${index} :: ${postSignature}\nsdkPost${index}${f.results ? ' _' : ''} = postReturn 0\n`;
    }
    else
    {
      mapping.imports[raw] = [f.module, fn.name];
      host += `\nforeign import ccall unsafe "${raw}" ${binder} :: ${signature}\n${publicName} :: ${fn.params
        .map(p => hsType(p.type))
        .concat([`IO (${fn.result == null ? '()' : hsType(fn.result)})`])
        .join(
          ' -> ',
        )}\n${publicName} ${args.join(' ')} = withArena $ \\arena -> do\n`;
      if (f.indirectParams)
      {
        host += `  arguments <- allocate arena ${f.paramSize}\n`;
        host += fn.params
          .map(
            (p, i) =>
              `  store ${codec(p.type)} arena (arguments \`plusPtr\` ${f.paramOffsets[i]}) a${i}\n`,
          )
          .join('');
        host += '  let values = [fromIntegral (address arguments) :: Word64]\n';
      }
      else
        host += `  values <- concat <$> sequence [${fn.params.map((p, i) => `lower ${codec(p.type)} arena a${i}`).join(', ')}]\n`;
      const argc = f.params - (f.retptr ? 1 : 0),
        names = Array.from({length: argc}, (_, i) => `r${i}`);
      if (f.retptr) host += `  result <- allocate arena (byteSize ${result})\n`;
      host += `  case values of\n    [${names.join(', ')}] -> do\n`;
      if (f.retptr)
        host += `      ${binder} ${names.map(x => '(fromIntegral ' + x + ')').join(' ')} (address result)\n      load ${result} Owned result\n`;
      else if (f.results)
        host += `      result <- ${binder} ${names.map(x => '(fromIntegral ' + x + ')').join(' ')}\n      runLift ${result} Owned [fromIntegral result]\n`;
      else
        host += `      ${binder} ${names.map(x => '(fromIntegral ' + x + ')').join(' ')}\n`;
      host += `    _ -> fail "canonical ABI argument count"\n`;
    }
  }
  for (const r of resources)
  {
    const raw = `sdk_drop_${r.id}`,
      n = name(r.id);
    if (r.export)
    {
      for (const operation of ['new', 'rep', 'drop'])
        mapping.imports[`sdk_${operation}_${r.id}`] = [
          `[export]${r.module}`,
          `[resource-${operation}]${r.name}`,
        ];
      types += `\nforeign import ccall unsafe "sdk_new_${r.id}" sdkNew${r.id} :: Word32 -> IO Word32\nforeign import ccall unsafe "sdk_rep_${r.id}" sdkRep${r.id} :: Word32 -> IO Word32\nforeign import ccall safe "sdk_drop_${r.id}" sdkDrop${r.id} :: Word32 -> IO ()\nnew${n} :: ResourceTypes.${n} -> IO ${n}\nnew${n} value = ${n} <$> newGuestResource sdkNew${r.id} value\nread${n} :: ${n} -> IO ResourceTypes.${n}\nread${n} (${n} value) = readGuestResource sdkRep${r.id} value\ndrop${n} :: ${n} -> IO ()\ndrop${n} (${n} value) = takeGuestHandle value >>= sdkDrop${r.id}\ndestroy${n} :: Word32 -> IO ()\ndestroy${n} = destroyGuestResource ResourceTypes.destroy${n}\n`;
      mapping.exports[`sdk_dtor_${r.id}`] = `${r.module}#[dtor]${r.name}`;
      linker.push(`sdk_dtor_${r.id}`);
      bindings += `\nforeign export ccall "sdk_dtor_${r.id}" sdkDtor${r.id} :: Word32 -> IO ()\nsdkDtor${r.id} :: Word32 -> IO ()\nsdkDtor${r.id} = destroy${n}\n`;
      host += `\nwith${n} :: IO ${n} -> (${n} -> IO a) -> IO a\nwith${n} create = bracket create drop${n}\n`;
      continue;
    }
    mapping.imports[raw] = [r.module, `[resource-drop]${r.name}`];
    host += `\nforeign import ccall unsafe "${raw}" sdkDrop${r.id} :: Word32 -> IO ()\nwith${n} :: IO ${n} -> (${n} -> IO a) -> IO a\nwith${n} create = bracket create (\\(${n} handle) -> sdkDrop${r.id} handle)\n`;
  }
  const shim = `(module\n (import "guest" "sdk_core_initialize" (func $initialize))\n (import "guest" "hs_init" (func $hs_init (param i32 i32)))\n (import "guest" "realloc" (func $realloc (param i32 i32) (result i32)))\n (func (export "_initialize") (call $initialize) (call $hs_init (i32.const 0) (i32.const 0)))\n (func (export "cabi_realloc") (param $old i32) (param $oldsize i32) (param $align i32) (param $size i32) (result i32)\n  (if (i32.gt_u (local.get $align) (i32.const 16)) (then unreachable))\n  (call $realloc (local.get $old) (local.get $size))))\n`;
  await mkdir(path.join(out, 'Internal'), {recursive: true});
  for (const [file, contents] of Object.entries({
    'Internal/Types.hs': types,
    'Host.hs': host,
    'Main.hs': bindings,
    'symbols.json': JSON.stringify(mapping, null, 2),
    'linker.json': JSON.stringify(linker),
    'initialize.wat': shim,
    'metadata.json': JSON.stringify(metadata, null, 2),
  }))
    await writeFile(path.join(out, file), contents);
  execFileSync(
    'ormolu',
    [
      '--mode',
      'inplace',
      ...['Internal/Types.hs', 'Host.hs', 'Main.hs'].map(file =>
        path.join(out, file),
      ),
    ],
    {stdio: 'inherit'},
  );
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
{
  const [wit, world, out] = process.argv.slice(2);
  if (!wit || !world || !out)
    throw new Error('usage: generate.mjs WIT WORLD OUTPUT');
  await generateBindings({wit, world, out});
}
